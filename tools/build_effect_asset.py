"""Embed the project-owned RGBA fire atlas; no runtime asset installation needed."""
from pathlib import Path
import hashlib
root=Path(__file__).resolve().parents[1]
asset=root/'assets/effects/vehicle-fire-atlas-v1.png';data=asset.read_bytes()
lines=['// Generated by tools/build_effect_asset.py; preserve the atlas alpha.','#pragma once',f'// PNG SHA-256: {hashlib.sha256(data).hexdigest()}','static const unsigned char FIRE_ATLAS_PNG[]={']
for start in range(0,len(data),24):lines.append(','.join(str(b) for b in data[start:start+24])+',')
lines+=['};',''];(root/'src/fire_atlas_data.h').write_text('\n'.join(lines))
print('Embedded fire atlas:',len(data),'PNG bytes')
