"""Explicit developer tool: fingerprint the supplied pristine GOG installations."""
import hashlib
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1]).resolve()
src = pathlib.Path(__file__).resolve().parents[1] / 'src'
text = (src / 'gamefiles.h').read_text()
required = re.findall(r'"([^"]+)"', text.split('GF_REQUIRED[] = {', 1)[1].split('};', 1)[0])
out = ['// Fingerprints only; no original game data. Generated by tools/generate_manifest.py.',
       '#pragma once',
       'struct GogFile { const char *name; const char *sha[3]; };',
       'static const char *const GOG_LANGUAGES[] = {"English", "French", "German"};',
       'static const GogFile GOG_FILES[] = {']
for name in required + ['MEGARACE2.gog']:
    hashes = []
    for lang in ('English', 'French', 'German'):
        p = root / ('Megarace 2 ' + lang) / name
        with p.open('rb') as f:
            hashes.append(hashlib.file_digest(f, 'sha256').hexdigest())
    out.append('  {"' + name + '", {' + ', '.join('"' + h + '"' for h in hashes) + '}},')
out += ['};', 'enum { GOG_FILE_COUNT = sizeof GOG_FILES / sizeof GOG_FILES[0] };', '']
(src / 'gog_manifest.h').write_text('\n'.join(out), encoding='utf-8')
print('Generated', len(required) + 1, 'fingerprints per language')
