"""Embed unmodified upstream GLSL and HQ2x LUT. No network is used when rebuilding.

OpenMR2 supplies only the GL 3.3 stage preamble and a gl_VertexID vertex adapter.
See src/third_party/output_filters/ for full upstream sources and license texts.
"""
from pathlib import Path
import hashlib, json
root=Path(__file__).resolve().parents[1]
folder=root/'src/third_party/output_filters'
out=['// Generated by tools/build_output_filters.py. Retain upstream sources/licenses.']
for name,file in [('HQ2X','hq2x.glsl'),('XBRZ','xbrz-freescale.glsl')]:
    source=(folder/file).read_text(encoding='utf-8')
    assert ')filter"' not in source
    out.append(f'static const char *FS_{name} = R"filter(#version 330 core\n#define FRAGMENT\n'+source+')filter";')
lut=(folder/'hq2x.png').read_bytes()
out.append('static const unsigned char HQ2X_LUT_PNG[] = {')
out += ['  '+','.join(map(str,lut[i:i+32]))+',' for i in range(0,len(lut),32)]
out+=['};','']
(root/'src/output_filter_data.h').write_text('\n'.join(out),encoding='utf-8')
records={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in folder.iterdir() if p.is_file() and p.name!='SHA256SUMS.json'}
(folder/'SHA256SUMS.json').write_text(json.dumps(records,indent=2),encoding='utf-8')
print('Embedded HQ2x shader/LUT and xBRZ shader.')
