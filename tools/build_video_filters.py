"""Embed upstream HQ4x/xBR shaders, their LUT and GL3.3 vertex adapters."""
from pathlib import Path
import json,hashlib,re
root=Path(__file__).resolve().parents[1];folder=root/'src/third_party/video_filters'
out=['// Generated by tools/build_video_filters.py. Preserve upstream licenses.']
for name,file in [('HQ_PATTERN','hqx-pass1.glsl'),('HQ_BLEND','hqx-pass2.glsl'),('XBR','xbr-lv2.glsl')]:
 text=(folder/file).read_text();text=re.sub(r'^#version[^\n]*','',text,flags=re.M)
 if name=='HQ_BLEND':text=text.replace('#define SCALE 2.','#define SCALE 4.')
 if name=='XBR':text=text.replace('#define XBR_SCALE 3.0','#define XBR_SCALE 4.0').replace('FragColor.xyz = res;','FragColor = vec4(res,1.0);')
 out.append('static const char *FS_VIDEO_'+name+'=R"video(#version 330 core\n#define FRAGMENT\n'+text+')video";')
vs_hq='''#version 330 core
uniform vec2 TextureSize;out vec4 TEX0,t1,t2,t3;
void main(){vec2 c=vec2(float(gl_VertexID&1),float((gl_VertexID>>1)&1));gl_Position=vec4(c*2.0-1.0,0,1);TEX0=vec4(c,0,1);vec2 p=1.0/TextureSize;t1=c.xxxy+vec4(-p.x,0,p.x,-p.y);t2=c.xxxy+vec4(-p.x,0,p.x,0);t3=c.xxxy+vec4(-p.x,0,p.x,p.y);}
'''
vs_xbr='''#version 330 core
uniform vec2 TextureSize;out vec2 texCoord;out vec4 t1,t2,t3,t4,t5,t6,t7;
void main(){vec2 c=vec2(float(gl_VertexID&1),float((gl_VertexID>>1)&1));gl_Position=vec4(c*2.0-1.0,0,1);texCoord=c;float dx=1.0/TextureSize.x,dy=1.0/TextureSize.y;t1=c.xxxy+vec4(-dx,0,dx,-2.0*dy);t2=c.xxxy+vec4(-dx,0,dx,-dy);t3=c.xxxy+vec4(-dx,0,dx,0);t4=c.xxxy+vec4(-dx,0,dx,dy);t5=c.xxxy+vec4(-dx,0,dx,2.0*dy);t6=c.xyyy+vec4(-2.0*dx,-dy,0,dy);t7=c.xyyy+vec4(2.0*dx,-dy,0,dy);}
'''
for index,name in enumerate(('texCoord','t1','t2','t3','t4','t5','t6','t7')):
 vs_xbr=re.sub(r'\b'+name+r'\b','TEX'+str(index),vs_xbr)
out+=['static const char *VS_VIDEO_HQ=R"video('+vs_hq+')video";', 'static const char *VS_VIDEO_XBR=R"video('+vs_xbr+')video";']
data=(folder/'hq4x.png').read_bytes();out.append('static const unsigned char VIDEO_HQ4X_LUT[]={'+','.join(map(str,data))+'};')
(root/'src/video_filter_data.h').write_text('\n'.join(out)+'\n')
(folder/'provenance.json').write_text(json.dumps({'repository':'https://github.com/libretro/glsl-shaders','retrieved':'2026-10-18','hq4x':'hqx/shader-files/hqx-pass1.glsl + hqx-pass2.glsl and hqx/resources/hq4x.png; LGPL-2.1-or-later','xbr':'xbr/shaders/xbr-lv2.glsl, MIT; sampled at 4x','sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in folder.iterdir() if p.is_file() and p.name!='provenance.json'}},indent=2))
print('Embedded GPU HQ4x and xBR-lv2 with original LUT/source notices')
