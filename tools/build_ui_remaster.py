"""Package reviewed Imagegen sprite sheets as embedded, palette-keyed UI assets.

This is deterministic sprite extraction/packing, not an AI upscale substitute.
Run prepare_ui_remaster.py first. Original game assets remain read-only.
"""
from pathlib import Path
import argparse, json, shutil
from PIL import Image

root = Path(__file__).resolve().parents[1]
inputs = root/'build/ui-remaster-input'
assets = root/'assets/revived_ui'
assets.mkdir(parents=True, exist_ok=True)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--generated-dir', type=Path,
                    help='Optional directory of raw Imagegen outputs; otherwise use the stored sheets.')
args = parser.parse_args()
generated = args.generated_dir
sources = {'hud': 'exec-068d8ccc-577e-4a93-aac1-3efec803a977.png',
           'arsenal_buttons': 'exec-67945179-d67a-4f3e-b423-f4af161a0ed6.png',
           'arsenal': 'exec-31df1f65-85c7-41e1-aa20-f72d8bbd097e.png',
           'controls': 'exec-70f44287-b18b-44f8-ac10-3407da35dca1.png'}
catalog = json.loads((inputs/'catalog.json').read_text())
header = ['// Generated by tools/build_ui_remaster.py; selected Imagegen outputs.',
          'struct RemasteredUIEntry { const char *key; const unsigned char *png; int bytes,asset; };']
entries = []
def solid_tile_bbox(image):
    # Ignore disconnected almost-transparent speckles left in generated gutters.
    mask=bytearray(1 if a>=128 else 0 for a in image.getchannel('A').getdata())
    width,height=image.size;best_count=0;best=None
    for start in range(len(mask)):
        if not mask[start]:continue
        mask[start]=0;queue=[start];left=right=start%width;top=bottom=start//width
        for point in queue:
            x,y=point%width,point//width;left=min(left,x);right=max(right,x);top=min(top,y);bottom=max(bottom,y)
            for xx,yy in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
                if 0<=xx<width and 0<=yy<height:
                    index=yy*width+xx
                    if mask[index]:mask[index]=0;queue.append(index)
        if len(queue)>best_count:best_count=len(queue);best=(left,top,right+1,bottom+1)
    assert best and best_count>width*height//8
    # Fixed alpha guard retained equally around every approved shop tile.
    return (max(0,best[0]-2),max(0,best[1]-2),min(width,best[2]+2),min(height,best[3]+2))
for category, filename in sources.items():
    selected = assets/(category+'-generated.png')
    if generated is not None and (generated/filename).exists(): shutil.copy2(generated/filename, selected)
    atlas = Image.open(selected).convert('RGBA')
    manifest = json.loads((inputs/(category+'-manifest.json')).read_text())
    columns, rows = manifest['columns'], manifest['rows']
    for e in manifest['entries']:
        assert e['remaster_enabled']
        col, row = e['cell']
        cell = atlas.crop((round(col*atlas.width/columns), round(row*atlas.height/rows),
                           round((col+1)*atlas.width/columns), round((row+1)*atlas.height/rows)))
        bbox = solid_tile_bbox(cell) if category=='arsenal_buttons' else cell.getchannel('A').getbbox()
        assert bbox, (category, e['id'])
        size=(400,328) if category=='arsenal_buttons' else (e['w']*8,e['h']*8)
        sprite = cell.crop(bbox).resize(size, Image.Resampling.LANCZOS)
        path = assets/f"sprite-{e['id']:03}.png"
        sprite.save(path)
        data = path.read_bytes()
        header.append(f"static const unsigned char REMASTERED_UI_{e['id']}[]={{"+
                      ','.join(str(n) for n in data)+'};')
        e['asset_png'] = path.name
        catalog[e['id']]['asset_png'] = path.name
        for key in e['source_keys']:
            entries.append(f'{{"{key}",REMASTERED_UI_{e["id"]},sizeof REMASTERED_UI_{e["id"]},{e["id"]}}}')
header.append('static const RemasteredUIEntry REMASTERED_UI_ENTRIES[]={'+',\n'.join(entries)+'};')
header.append('static const int REMASTERED_UI_ASSETS=68;')
(root/'src/remastered_ui_data.h').write_text('\n'.join(header)+'\n')
(assets/'catalog.json').write_text(json.dumps(catalog, indent=2)+'\n')
print(f'Embedded {sum(e["remaster_enabled"] for e in catalog)} sprites, {len(entries)} exact palette-qualified keys; background buttons excluded.')
