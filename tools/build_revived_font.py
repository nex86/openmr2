"""Rebuild the embedded Revived SDF atlas; requires Pillow, numpy and scipy.

Rajdhani SemiBold, Indian Type Foundry, SIL OFL 1.1 (assets/fonts/OFL.txt).
Source: https://github.com/google/fonts/tree/main/ofl/rajdhani
The original game fonts are never modified. Runtime needs no external font file.
"""
from pathlib import Path
from io import BytesIO
from PIL import Image, ImageDraw, ImageFont
import numpy as np
from scipy.ndimage import distance_transform_edt

root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(str(root / 'assets/fonts/Rajdhani-SemiBold.ttf'), 96)
cap = font.getbbox('H', anchor='ls')[3] - font.getbbox('H', anchor='ls')[1]
atlas = Image.new('L', (2048, 2048))
glyphs = []
for c in range(32, 256):
    ch = chr(c)
    box = font.getbbox(ch, anchor='ls')
    x0, y0, x1, y1 = box
    w, h = max(1, x1-x0+16), max(1, y1-y0+16)
    tile = Image.new('L', (w, h))
    ImageDraw.Draw(tile).text((8-x0, 8-y0), ch, font=font, fill=255, anchor='ls')
    mask = np.asarray(tile) >= 128
    if mask.any():
        distance = distance_transform_edt(mask) - distance_transform_edt(~mask)
        field = np.clip(128 + distance*16, 0, 255).astype(np.uint8)
    else:
        field = np.zeros((h, w), dtype=np.uint8)
    x, y = ((c-32)%16)*128, ((c-32)//16)*144
    assert w <= 128 and h <= 144
    atlas.paste(Image.fromarray(field), (x, y))
    glyphs.append((x,y,w,h,x0-8,y0-8,round(font.getlength(ch))))
buf = BytesIO()
atlas.save(buf, format='PNG', optimize=True)
data = buf.getvalue()
out = ['// Generated by tools/build_revived_font.py; Rajdhani SemiBold, SIL OFL 1.1.',
       'struct RevivedGlyph { int x,y,w,h,left,top,advance; };',
       f'static const int REVIVED_CAP = {cap};',
       'static const RevivedGlyph REVIVED_GLYPHS[224] = {']
out += ['  {'+','.join(map(str,g))+'},' for g in glyphs]
out += ['};', 'static const unsigned char REVIVED_FONT_PNG[] = {']
out += ['  '+','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32)]
out += ['};', '']
(root/'src/revived_font_data.h').write_text('\n'.join(out), encoding='utf-8')
atlas.save(root/'assets/fonts/Revived-SDF.png')
print(f'Embedded {len(data)} bytes; {len(glyphs)} Latin-1 glyphs, cap height {cap}')
