"""Embed the unmodified MIT-licensed AMD FSR1 headers and GL3.3 adapter."""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1];upstream=root/'src/third_party/fsr1'
prefix='''#version 330 core
#extension GL_ARB_shading_language_packing : require
#extension GL_ARB_gpu_shader5 : require
#define A_GPU 1
#define A_GLSL 1
#define FSR_EASU_F 1
#define FSR_RCAS_F 1
'''
adapter='''
vec4 sampleClamp(ivec2 p){return texelFetch(uSource,clamp(p,ivec2(0),textureSize(uSource,0)-ivec2(1)),0);}
vec4 gatherChannel(vec2 p,int channel){ivec2 b=ivec2(floor(p*vec2(textureSize(uSource,0))-0.5));return vec4(sampleClamp(b+ivec2(0,1))[channel],sampleClamp(b+ivec2(1,1))[channel],sampleClamp(b+ivec2(1,0))[channel],sampleClamp(b)[channel]);}
vec4 FsrEasuRF(vec2 p){return gatherChannel(p,0);}
vec4 FsrEasuGF(vec2 p){return gatherChannel(p,1);}
vec4 FsrEasuBF(vec2 p){return gatherChannel(p,2);}
vec4 FsrRcasLoadF(ivec2 p){return sampleClamp(p);}
void FsrRcasInputF(inout float r,inout float g,inout float b){}
void main(){vec3 color;if(uStage==0){uvec4 c0,c1,c2,c3;vec2 size=vec2(textureSize(uSource,0));FsrEasuCon(c0,c1,c2,c3,size.x,size.y,size.x,size.y,uOutput.x,uOutput.y);FsrEasuF(color,uvec2(gl_FragCoord.xy),c0,c1,c2,c3);}else{uvec4 con;FsrRcasCon(con,0.85);FsrRcasF(color.r,color.g,color.b,uvec2(gl_FragCoord.xy),con);}o=vec4(clamp(color,0.0,1.0),1.0);}
'''
fsr=(upstream/'ffx_fsr1.h').read_text().replace('con3[2]=con3[3]=0;','con3[2]=con3[3]=0u;').replace('con[2]=0;','con[2]=0u;').replace('con[3]=0;','con[3]=0u;')
# GLSL 3.3 needs an explicit unsigned literal; upstream files stay unmodified.
shader=prefix+(upstream/'ffx_a.h').read_text()+'\nuniform sampler2D uSource;uniform vec2 uOutput;uniform int uStage;out vec4 o;\n'+fsr+adapter
(root/'src/video_fsr_data.h').write_text('// Generated by tools/build_video_fsr.py. AMD FSR1 MIT license: third_party/fsr1/LICENSE.txt\nstatic const char *FS_VIDEO_FSR=R"FSR('+shader+')FSR";\n')
(upstream/'provenance.json').write_text(json.dumps({'repository':'https://github.com/GPUOpen-Effects/FidelityFX-FSR','retrieved':'2026-10-18','source_files':'ffx-fsr/ffx_a.h and ffx-fsr/ffx_fsr1.h, unmodified','sha256':{p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in upstream.glob('*.h')}},indent=2))
print('Embedded official FSR1 EASU/RCAS shader')
